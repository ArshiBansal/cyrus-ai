#!/usr/bin/env node
/* ══ build-crawl-data.mjs — turn the raw GitHub crawl into site data ══
   Reads data/crawl/*.jsonl (written by scripts/crawl-github.mjs) and emits:

     src/data/issueSignals.ts   a small, hand-sized sample of real open issues
                                for the home page hero panel

   Everything here is derived from the crawl. Nothing is invented: if a field
   is missing upstream it stays missing, and the counts printed at the end are
   the counts the site will show.
*/
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CRAWL = resolve(ROOT, "data/crawl");
const OUT = resolve(ROOT, "src/data");

const readJsonl = (file) => {
  const p = resolve(CRAWL, file);
  if (!existsSync(p)) return [];
  return readFileSync(p, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
};

const issues = readJsonl("issues.jsonl");
if (!issues.length) {
  console.error("no issues in data/crawl/issues.jsonl - run scripts/crawl-github.mjs --phase issues first");
  process.exit(1);
}

const HELPFUL = /good first issue|help wanted|beginner|easy|starter|difficulty easy/i;
const now = Date.now();
const days = (iso) => (now - new Date(iso).getTime()) / 864e5;

/* pick issues that a contributor could realistically still take:
   open, unlocked, nobody assigned, recently touched, from a well-used repo.
   Beginner-labelled ones come first because that is what a stranger needs. */
const candidates = issues
  .filter((i) => i.state === "open" && !i.locked)
  .filter((i) => !(i.assignees ?? []).length)
  .filter((i) => days(i.updated_at) < 45)
  .filter((i) => (i.repo_stars ?? 0) >= 2000)
  .filter((i) => (i.title ?? "").trim().length > 12)
  .map((i) => ({
    ...i,
    helpful: HELPFUL.test((i.labels ?? []).join(" ")) ? 1 : 0,
    heat: (i.reactions ?? 0) + (i.comments ?? 0),
  }))
  .sort((a, b) => b.helpful - a.helpful || b.repo_stars - a.repo_stars || days(a.updated_at) - days(b.updated_at));

/* at most two per repository so the wall reads as a wide ecosystem */
const perRepo = new Map();
const picked = [];
for (const i of candidates) {
  const n = perRepo.get(i.repo) ?? 0;
  if (n >= 2) continue;
  perRepo.set(i.repo, n + 1);
  picked.push(i);
  if (picked.length === 30) break;
}

const rows = picked.map((i) => ({
  repo: i.repo,
  title: i.title.trim().replace(/\s+/g, " ").slice(0, 120),
  url: i.url,
  number: i.number,
  stars: i.repo_stars,
  lang: i.repo_language ?? null,
  labels: (i.labels ?? []).slice(0, 3),
  updated: i.updated_at.slice(0, 10),
  beginner: !!i.helpful,
}));

writeFileSync(
  resolve(OUT, "issueSignals.ts"),
  `/* GENERATED by scripts/build-crawl-data.mjs from data/crawl/issues.jsonl.
   ${rows.length} real open issues, crawled ${new Date().toISOString().slice(0, 10)}.
   Do not edit by hand - rerun the script. */
export interface IssueSignal {
  repo: string; title: string; url: string; number: number;
  stars: number; lang: string | null; labels: string[];
  updated: string; beginner: boolean;
}

export const ISSUE_SIGNALS: IssueSignal[] = ${JSON.stringify(rows, null, 2)} as const;

/** when the sample was crawled, for the "fresh since" caption */
export const ISSUE_SIGNALS_AS_OF = "${new Date().toISOString().slice(0, 10)}";
`
);

console.log(`issueSignals.ts: ${rows.length} of ${issues.length} crawled issues, ${candidates.length} eligible`);
console.log(`repos represented: ${new Set(rows.map((r) => r.repo)).size}`);

/* ── the numbers the site is allowed to print ─────────────────
   Every figure here is a count of rows in the crawl, so the copy can
   say "we track N issues" and have it be literally true. */
const repos = readJsonl("repos.jsonl");
const langs = new Set(issues.map((i) => i.repo_language).filter(Boolean));
const orgs = new Set(issues.map((i) => i.org).filter(Boolean));
const issueRepos = new Set(issues.map((i) => i.repo));
const newest = issues.reduce((a, i) => (i.updated_at > a ? i.updated_at : a), "");
const beginnerLabelled = issues.filter((i) => HELPFUL.test((i.labels ?? []).join(" "))).length;

writeFileSync(
  resolve(OUT, "crawlStats.ts"),
  `/* GENERATED by scripts/build-crawl-data.mjs. Counts of rows in data/crawl/,
   so anything the site states from here is literally true of the snapshot.
   Do not edit by hand - rerun the script. */
export const CRAWL = {
  issues: ${issues.length},
  reposWithIssues: ${issueRepos.size},
  catalogRepos: ${repos.length},
  orgs: ${orgs.size},
  languages: ${langs.size},
  beginnerLabelled: ${beginnerLabelled},
  mostRecentUpdate: "${newest.slice(0, 10)}",
  crawledAt: "${new Date().toISOString().slice(0, 10)}",
} as const;
`
);
console.log(`crawlStats.ts: ${issues.length} issues / ${issueRepos.size} repos / ${repos.length} catalog / ${orgs.size} orgs`);
