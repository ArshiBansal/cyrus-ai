#!/usr/bin/env node
/* ══ build-leaderboard.mjs — data/crawl/leaderboard.jsonl -> src/data/leaderboard.ts
   The crawl stores one row per contributor with GitHub's own author-scoped
   search totals. This file only shapes that into something the site can
   import: it drops nothing, renumbers nothing, and rounds nothing. The bot
   flag is written out so the dataset says what it is, and the humans are
   pre-ranked by merged PRs because that is the column the page opens on.
     node scripts/build-leaderboard.mjs
   ═════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync } from "node:fs";

const IN = "data/crawl/leaderboard.jsonl";
const OUT = "src/data/leaderboard.ts";

const rows = readFileSync(IN, "utf8").split("\n").filter((l) => l.trim()).map((l) => JSON.parse(l));

/* mirrors isBot() in src/lib/leaderboard.ts - keep the two in step */
const isBot = (login, avatar = "") =>
  /\[bot\]$/i.test(login) || /avatars\.githubusercontent\.com\/in\/\d+/.test(avatar) || /bot$/i.test(login);

const n = (v) => (typeof v === "number" && Number.isFinite(v) ? v : null);
const clip = (s, k) => (typeof s === "string" && s.length > k ? s.slice(0, k - 1).trimEnd() + "…" : s || null);

const clean = rows.map((r) => ({
  login: r.login,
  avatar: r.avatar,
  html: r.html,
  name: clip(r.name, 60),
  company: clip(r.company, 48),
  location: clip(r.location, 40),
  followers: n(r.followers),
  public_repos: n(r.public_repos),
  joined: r.created_at ? String(r.created_at).slice(0, 10) : null,
  merged_total: n(r.merged_total),
  open_total: n(r.open_total),
  reviews_total: n(r.reviews_total),
  discovered_in_sample: n(r.discovered_in_sample) ?? 0,
  bot: isBot(r.login, r.avatar),
}));

const byMerged = [...clean].sort((a, b) => (b.merged_total ?? 0) - (a.merged_total ?? 0) || a.login.localeCompare(b.login, "en"));

const humans = byMerged.filter((r) => !r.bot);
const botRows = byMerged.filter((r) => r.bot);

const one = (r) =>
  "  { " +
  [
    `login: ${JSON.stringify(r.login)}`,
    `avatar: ${JSON.stringify(r.avatar)}`,
    `html: ${JSON.stringify(r.html)}`,
    `name: ${JSON.stringify(r.name)}`,
    `company: ${JSON.stringify(r.company)}`,
    `location: ${JSON.stringify(r.location)}`,
    `followers: ${r.followers}`,
    `public_repos: ${r.public_repos}`,
    `joined: ${JSON.stringify(r.joined)}`,
    `merged_total: ${r.merged_total}`,
    `open_total: ${r.open_total}`,
    `reviews_total: ${r.reviews_total}`,
    `discovered_in_sample: ${r.discovered_in_sample}`,
  ].join(", ") +
  " }";

const body = `/* ══ leaderboard.ts — GENERATED by scripts/build-leaderboard.mjs. Do not edit by hand.
   Source: data/crawl/leaderboard.jsonl, written by scripts/crawl-github.mjs
   phase "authors". Every person here was found by sampling pull requests
   merged since 2025-01-01 across the tracked languages; merged_total,
   open_total and reviews_total are GitHub search total_count values for
   that author, all time, exactly as GitHub reported them on ${new Date().toISOString().slice(0, 10)}.
   LEADERS is humans only, ordered by merged_total. BOTS is everything the
   classifier in src/lib/leaderboard.ts calls a machine, kept out of the
   ranking but on disk so the page can say how much of the traffic it
   filtered. ══ */
import type { LeaderRow } from "../lib/leaderboard";

export const LEADERS: LeaderRow[] = [
${humans.map(one).join(",\n")},
];

export const BOTS: LeaderRow[] = [
${botRows.map(one).join(",\n")},
];

/** the sample window the pool was drawn from, for the methodology block */
export const BOARD_META = {
  crawledAt: ${JSON.stringify(new Date().toISOString().slice(0, 10))},
  since: "2025-01-01",
  pool: ${clean.length},
  humans: ${humans.length},
  bots: ${botRows.length},
  mergedByHumans: ${humans.reduce((s, r) => s + (r.merged_total ?? 0), 0)},
  top100Merged: ${humans.slice(0, 100).reduce((s, r) => s + (r.merged_total ?? 0), 0)},
} as const;
`;

writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${humans.length} humans, ${botRows.length} bots, top-100 merged ${humans.slice(0, 100).reduce((s, r) => s + (r.merged_total ?? 0), 0)}`);
